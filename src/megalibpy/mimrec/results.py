"""In-memory Mimrec histograms read by an isolated ROOT Python process."""

from dataclasses import dataclass
import json
from pathlib import Path
import re
import subprocess
import sys
import tempfile

import numpy as np
from astropy.coordinates import SkyCoord
import astropy.units as u

from ..execution import ExecutionResult, MEGAlibRuntime


class ROOTExtractionError(RuntimeError):
    """The ROOT subprocess failed, or histogram selection was ambiguous.

    The exception message contains child diagnostics or candidate object paths.
    This read operation does not create an execution record in the manifest.
    """


@dataclass(frozen=True)
class ROOTObject:
    """A discovered TH1/TH2 histogram (profiles and TH3 are excluded).

    Attributes
    ----------
    object_path : str
        Exact selector including directory key cycles and Canvas/Pad names.
        Names are URL-escaped; duplicate primitive names receive a 1-based
        occurrence suffix. Unnamed primitives use ``@unnamed``.
    name, class_name, title : str
        Original ROOT name, concrete class and title, respectively.
    dimension : int
        One for spectra or two for images.
    x_title, y_title, z_title : str
        Unmodified ROOT axis titles; an empty title remains empty.
    """

    object_path: str
    name: str
    class_name: str
    title: str
    dimension: int
    x_title: str
    y_title: str
    z_title: str


@dataclass(frozen=True)
class HistogramAxis:
    """Detached numerical bin axis with its original title and optional unit.

    Attributes
    ----------
    edges : numpy.ndarray
        Float64 array of length N+1, excluding underflow/overflow edges.
    title : str
        Original ROOT axis title.
    unit : str or None
        Literal trailing bracketed unit, e.g. ``"keV"`` or ``"deg"``.
        None means no bracketed unit was supplied; no unit is inferred.
    """

    edges: np.ndarray
    title: str
    unit: str | None

    @property
    def centers(self):
        """numpy.ndarray: Arithmetic bin centers in the axis unit."""
        return self.edges[:-1] + self.widths / 2

    @property
    def widths(self):
        """numpy.ndarray: Per-bin widths in the axis unit."""
        return np.diff(self.edges)


@dataclass(frozen=True)
class SpectrumData:
    """Detached 1D histogram; no files are generated by this result.

    Attributes
    ----------
    path : pathlib.Path
        Resolved input ROOT filename.
    object : ROOTObject
        Exact source object and axis titles.
    axis : HistogramAxis
        Energy or other native X axis, including all regular bin edges.
    values : numpy.ndarray
        Float64 contents of regular bins, without normalization or rescaling.
    value_title : str
        Unmodified Y-axis title.
    value_unit : str or None
        ``"counts/keV"`` or ``"counts"`` for exact recognized count labels;
        otherwise the bracketed unit, or None. The raw title is always retained.
    flow_values : tuple of float
        Underflow and overflow contents in the original histogram convention.
        They are excluded from total_counts; density flow bins have no finite
        energy width and are not integrated.
    """

    path: Path
    object: ROOTObject
    axis: HistogramAxis
    values: np.ndarray
    value_title: str
    value_unit: str | None
    flow_values: tuple[float, float]

    @property
    def total_counts(self):
        """float: Counts in regular bins, only for verified count conventions.

        ``counts/keV`` with X unit ``keV`` uses sum(values * bin widths).
        An exact ``counts`` label uses sum(values). Unknown labels, rates,
        normalized histograms, profiles and inconsistent units are never
        blindly width-integrated.

        Raises
        ------
        ValueError
            The histogram labels do not establish one of these conventions,
            or the values are nonfinite.
        """
        if not np.all(np.isfinite(self.values)):
            raise ValueError("Nonfinite spectrum values cannot produce total counts")
        label = _count_unit(self.value_title)
        if label == "counts/keV" and self.axis.unit == "keV":
            return float(np.sum(self.values * self.axis.widths))
        if label == "counts":
            return float(np.sum(self.values))
        raise ValueError("Histogram labels do not establish counts or counts/keV with a keV axis")


@dataclass(frozen=True)
class ImageData:
    """Detached 2D histogram with an explicitly defined pixel-maximum position.

    Attributes
    ----------
    path : pathlib.Path
        Resolved input ROOT filename.
    object : ROOTObject
        Selected object metadata and original titles.
    x_axis, y_axis : HistogramAxis
        Native histogram axes. Their edges are never reversed or projected.
    values : numpy.ndarray
        Float64 contents, shape (Nx, Ny): values[ix, iy] follows ROOT X then Y.
        Flow bins are excluded. Use values.T for Matplotlib pcolormesh.
    value_title : str
        Original Z-axis title, without assuming intensity normalization.
    value_unit : str or None
        Bracketed Z-axis unit, e.g. ``"a.u."``, or None.
    longitude_mapping : dict or None
        Verified linear TGaxis mapping: longitude = scale * native_x + offset.
        Includes axis_title, coordinate_system and projection. Recognized only
        for an explicit horizontal Galactic Longitude [deg] TGaxis spanning
        the histogram and a Galactic Latitude [deg] Y axis. Otherwise None.
        In particular, Hammer images are not assumed to have a linear mapping.
    """

    path: Path
    object: ROOTObject
    x_axis: HistogramAxis
    y_axis: HistogramAxis
    values: np.ndarray
    value_title: str
    value_unit: str | None
    longitude_mapping: dict | None

    @property
    def peak_indices(self):
        """tuple of int: Zero-based (ix, iy) of a unique finite maximum.

        Raises
        ------
        ValueError
            No finite pixels exist, or several pixels share the maximum.
            Plateaus are ambiguous; no first-pixel or centroid rule is applied.
        """
        finite = np.isfinite(self.values)
        if not finite.any():
            raise ValueError("Image has no finite pixels")
        maximum = self.values[finite].max()
        indices = np.argwhere(finite & (self.values == maximum))
        if len(indices) != 1:
            raise ValueError(f"Image maximum is shared by {len(indices)} pixels")
        return tuple(int(i) for i in indices[0])

    @property
    def peak_position(self):
        """tuple of float: Native (x, y) bin center of the maximum pixel.

        This is a pixel maximum, not an intensity-weighted centroid or fitted
        source location. Units are those of x_axis/y_axis. Unknown axes remain
        histogram coordinates. See peak_indices for ambiguity errors and
        peak_galactic_position for the separately verified sky mapping.
        """
        ix, iy = self.peak_indices
        return float(self.x_axis.centers[ix]), float(self.y_axis.centers[iy])

    @property
    def peak_galactic_position(self) -> SkyCoord | None:
        """Return the maximum pixel center as a Galactic SkyCoord, or None.

        Returns
        -------
        astropy.coordinates.SkyCoord or None
            Scalar position with frame="galactic", longitude wrapped into
            [0, 360) degrees and latitude in degrees. Access .l.deg/.b.deg for
            numeric values, or use .separation() with another sky coordinate.
            None means no unique explicit rectangular Galactic mapping was
            verified; no coordinate frame or longitude sign is guessed.

        Raises
        ------
        ValueError
            A verified mapping exists but the peak is ambiguous/nonfinite, or
            its latitude is outside the Galactic coordinate range.

        Notes
        -----
        This is the maximum pixel's center, not a centroid or fitted location.
        peak_position remains the native (x, y) tuple. This property previously
        returned an (l, b) tuple; use position.l.deg and position.b.deg instead
        of unpacking that old return value. No equatorial transformation or
        inverse Hammer projection is performed.

        Examples
        --------
        >>> position = image.peak_galactic_position  # doctest: +SKIP
        >>> if position is not None:  # doctest: +SKIP
        ...     longitude, latitude = position.l.deg, position.b.deg
        """
        if self.longitude_mapping is None:
            return None
        x, y = self.peak_position
        mapping = self.longitude_mapping
        longitude = (mapping["scale"] * x + mapping["offset"]) % 360
        return SkyCoord(l=longitude * u.deg, b=y * u.deg, frame="galactic")

    @property
    def coordinate_system(self):
        """str: ``galactic`` for a verified mapping, otherwise ``unknown``.

        This describes the optional sky mapping, not the raw peak_position.
        """
        return "galactic" if self.longitude_mapping is not None else "unknown"

    @property
    def projection(self):
        """str: ``rectangular`` for a verified mapping, otherwise ``unknown``."""
        return "rectangular" if self.longitude_mapping is not None else "unknown"


def _bracket_unit(title):
    match = re.search(r"\[([^\[\]]+)\]\s*$", title)
    return match.group(1) if match else None


def _count_unit(title):
    label = re.sub(r"\s+", "", title).lower()
    if label in {"counts/kev", "cts/kev", "count/kev"}:
        return "counts/keV"
    if label in {"counts", "cts", "count"}:
        return "counts"
    return None


def _axis(data):
    edges = np.array(data["edges"], dtype=float)
    if edges.ndim != 1 or len(edges) < 2 or not np.isfinite(edges).all() or not (np.diff(edges) > 0).all():
        raise ROOTExtractionError("Histogram has invalid bin edges")
    return HistogramAxis(edges, data["title"], _bracket_unit(data["title"]))


def _input_path(input_data, group):
    if isinstance(input_data, ExecutionResult):
        if input_data.returncode != 0:
            raise ValueError("Cannot extract a failed execution result")
        if group is None:
            paths = [Path(p) for paths in input_data.outputs.values() for p in paths]
        else:
            paths = [Path(p) for p in input_data.outputs.get(group, ())]
        paths = sorted(set(p.expanduser().resolve() for p in paths if p.suffix.lower() == ".root"))
        if len(paths) != 1:
            raise ValueError(f"Expected one ROOT product in {group or 'all'} output groups; pass an explicit path: {paths}")
        path = paths[0]
    else:
        path = Path(input_data).expanduser().resolve()
    if not path.is_file():
        raise FileNotFoundError(path)
    return path


def _read(path, action, dimension, object_path, runtime, root_python, timeout):
    runtime = runtime if runtime is not None else MEGAlibRuntime.direct()
    python = root_python if root_python is not None else (
        "python" if runtime.setup_script is not None else sys.executable)
    if timeout is not None and timeout <= 0:
        raise ValueError("timeout must be positive or None")
    worker = Path(__file__).with_name("_root_worker.py")
    with tempfile.TemporaryDirectory(prefix="megalibpy-root-") as directory:
        temporary = Path(directory)
        request_path, response_path = temporary / "request.json", temporary / "response.json"
        request_path.write_text(json.dumps({"path": str(path), "action": action,
                                           "dimension": dimension, "object_path": object_path}), encoding="utf-8")
        command, env = runtime.launch(
            [str(python), str(worker), str(request_path), str(response_path)],
            temporary / "executable.txt")
        # ROOT and setup scripts may print to stdout; the structured response
        # uses a separate temporary file, never a native log or persistent cache.
        with (temporary / "stdout").open("wb") as stdout, (temporary / "stderr").open("wb") as stderr:
            try:
                completed = subprocess.run(command, env=env, cwd=temporary, stdout=stdout,
                                           stderr=stderr, timeout=timeout, check=False)
            except subprocess.TimeoutExpired as exc:
                raise ROOTExtractionError(f"ROOT extraction timed out after {timeout} seconds") from exc
        if completed.returncode != 0 or not response_path.is_file():
            diagnostics = (temporary / "stderr").read_text(errors="replace")
            raise ROOTExtractionError(f"ROOT reader exited {completed.returncode}: {diagnostics}")
        try:
            response = json.loads(response_path.read_text(encoding="utf-8"))
        except (ValueError, OSError) as exc:
            raise ROOTExtractionError("ROOT reader returned an invalid response") from exc
        if "error" in response:
            raise ROOTExtractionError(response["error"])
        return response["data"]


def list_root_objects(input_data, *, runtime=None, root_python=None, timeout=120):
    """Discover TH1/TH2 histograms recursively in directories and Canvas/Pad.

    Parameters
    ----------
    input_data : ExecutionResult or str or pathlib.Path
        A result with exactly one ROOT product across all groups, or a ROOT path.
    runtime : MEGAlibRuntime or None, optional
        None (default) uses direct execution. A setup-script runtime initializes
        ROOT in a separate child, allowing a Python 3.10 MEGAlib environment and
        a Python 3.12 caller. No PyROOT is imported into the caller.
    root_python : str or pathlib.Path or None, optional
        Child Python executable, default None: current Python for direct mode,
        or ``python`` resolved after setup for setup-script mode. Select the
        executable belonging to ROOT, never a different version's PyROOT path.
    timeout : float or None, optional
        Whole child-process timeout in seconds, default 120; None disables it.

    Returns
    -------
    tuple of ROOTObject
        Every supported histogram, with exact object_path selectors. All key
        cycles are included; no latest-cycle or fixed primitive index is used.
        TH3 and profiles are excluded. An empty file returns an empty tuple.

    Raises
    ------
    FileNotFoundError
        Input path, executable or setup script is missing.
    ValueError
        Result has multiple/no ROOT products, or timeout is not positive.
    ROOTExtractionError
        ROOT import/read fails, the child fails, or the timeout expires.

    Examples
    --------
    >>> objects = list_root_objects("spectrum.root", root_python="root-python")
    >>> selector = objects[0].object_path  # inspect candidates before choosing
    """
    path = _input_path(input_data, None)
    data = _read(path, "list", None, None, runtime, root_python, timeout)
    return tuple(ROOTObject(**meta) for meta in data["objects"])


def extract_spectrum(input_data, *, object_path=None, runtime=None, root_python=None, timeout=120):
    """Read one 1D spectrum into memory without writing persistent files.

    Parameters
    ----------
    input_data : ExecutionResult or str or pathlib.Path
        Mimrec spectrum result (one .root in outputs['spectrum']) or ROOT path.
        PNG products cannot be converted back to histogram bins.
    object_path : str or None, optional
        Exact selector from list_root_objects. Default None requires exactly one
        1D histogram; multiple candidates or key cycles require explicit choice.
    runtime : MEGAlibRuntime or None, optional
        Default None uses direct execution; a setup-script runtime initializes
        the independent ROOT child. The analysis process never imports PyROOT.
    root_python : str or pathlib.Path or None, optional
        ROOT-compatible child Python. Default None uses current Python in direct
        mode or ``python`` after setup. No megalibpy installation is needed in
        the child environment, only PyROOT and Python >=3.10.
    timeout : float or None, optional
        Child timeout in seconds, default 120; None disables the timeout.

    Returns
    -------
    SpectrumData
        Bin edges, contents, labels/units, separate underflow/overflow and source
        metadata. total_counts integrates only recognized counts/keV with keV
        bin widths, or sums explicitly labeled counts. Unknown conventions raise
        ValueError when total_counts is requested, not during extraction.

    Raises
    ------
    FileNotFoundError
        Input, executable or setup script is missing.
    ValueError
        The result has no unique ROOT spectrum product or timeout is invalid.
    ROOTExtractionError
        Histogram choice is ambiguous/missing, ROOT cannot read the file,
        PyROOT is unavailable in the child, or the child fails/times out.

    Notes
    -----
    Only regular bins contribute to total_counts. No exposure, flux, background
    or time scaling is performed. The input file and manifest are read-only.
    Temporary IPC files are removed on success and failure; no TSV/cache is kept.

    Examples
    --------
    >>> runtime = MEGAlibRuntime.from_setup_script("megalib-setup.sh")
    >>> spectrum = extract_spectrum("spectrum.root", runtime=runtime)
    >>> counts = spectrum.total_counts
    >>> edges, values = spectrum.axis.edges, spectrum.values
    """
    path = _input_path(input_data, "spectrum")
    data = _read(path, "extract", 1, object_path, runtime, root_python, timeout)
    return SpectrumData(path, ROOTObject(**data["object"]), _axis(data["x"]),
                        np.array(data["values"], dtype=float), data["value_title"],
                        _count_unit(data["value_title"]) or _bracket_unit(data["value_title"]),
                        tuple(data["flow_values"]))


def extract_image(input_data, *, object_path=None, runtime=None, root_python=None, timeout=120):
    """Read one 2D image, preserving native bins and explicit coordinate metadata.

    Parameters
    ----------
    input_data : ExecutionResult or str or pathlib.Path
        Mimrec image result (one .root in outputs['image']) or a ROOT path.
    object_path : str or None, optional
        Exact list_root_objects selector. Default None requires one 2D histogram;
        multiple candidates/cycles require selection, never a latest-file rule.
    runtime : MEGAlibRuntime or None, optional
        None (default) uses direct execution. Setup mode initializes a separate
        ROOT child; no PyROOT is loaded into the calling analysis Python.
    root_python : str or pathlib.Path or None, optional
        ROOT-compatible Python executable. None uses current Python in direct
        mode or ``python`` after setup. Child requires PyROOT and Python >=3.10.
    timeout : float or None, optional
        Child-process timeout in seconds, default 120; None disables it.

    Returns
    -------
    ImageData
        Contents indexed [x, y], native bin edges/titles/units, and metadata.
        peak_position is the unique maximum pixel's native bin center, not a
        centroid. peak_galactic_position is a scalar Galactic SkyCoord, available
        only for a verified rectangular Galactic TGaxis mapping; unknown projections and
        Hammer images remain unmapped. Tied maxima raise ValueError on access.

    Raises
    ------
    FileNotFoundError
        Input, executable or setup script is missing.
    ValueError
        Result has no unique ROOT image product or timeout is invalid.
    ROOTExtractionError
        Histogram choice is ambiguous/missing, ROOT read/import fails, or child
        execution fails/times out.

    Notes
    -----
    No longitude sign rule is hardcoded. Coordinates and intensity are not
    reprojected, normalized or fitted. Flow bins are omitted. Files/manifests
    are unmodified, and temporary IPC files are removed; no image/TSV is saved.

    Examples
    --------
    >>> image = extract_image("image.root", root_python="root-python")
    >>> x, y = image.peak_position  # native histogram bin center
    >>> galactic = image.peak_galactic_position  # Galactic SkyCoord or None
    """
    path = _input_path(input_data, "image")
    data = _read(path, "extract", 2, object_path, runtime, root_python, timeout)
    return ImageData(path, ROOTObject(**data["object"]), _axis(data["x"]), _axis(data["y"]),
                     np.array(data["values"], dtype=float), data["value_title"],
                     _bracket_unit(data["value_title"]), data["mapping"])
